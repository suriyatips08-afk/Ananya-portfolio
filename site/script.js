function renderProjects(filter = 'all') {
  const grid = qs('#project-grid');
  const visible = projects.filter(project => filter === 'all' || project.filters.includes(filter));
  grid.innerHTML = visible.map((project) => {
    const index = projects.indexOf(project);
    return `<article class="project-card" data-index="${index}" tabindex="0" aria-label="Open case study: ${project.title}">
      <div class="project-card__media"><span class="project-card__number mono">${String(index + 1).padStart(2,'0')}</span><img src="${project.cover}" alt="${project.alt}" loading="lazy"><span class="project-card__view mono">VIEW →</span></div>
      <div class="project-card__meta"><span class="project-card__index mono">${String(index + 1).padStart(2,'0')}</span><div><h3>${project.title}</h3><span class="mono">${project.category}</span></div><p class="project-card__desc">${project.intro}</p><div class="project-card__tags mono">${project.tags.map(tag => `<span>${tag}</span>`).join('')}</div></div>
    </article>`;
  }).join('');
  bindCards();
  if (!reducedMotion && window.gsap) {
    gsap.fromTo(qsa('.project-card', grid), { opacity: 0, y: 24 }, { opacity: 1, y: 0, duration: .7, stagger: .06, ease: 'power3.out', clearProps: 'transform' });
  }
}

function bindCards() {
  qsa('.project-card').forEach(card => {
    card.addEventListener('click', () => openCase(Number(card.dataset.index)));
    card.addEventListener('keydown', (event) => { if (event.key === 'Enter' || event.key === ' ') { event.preventDefault(); openCase(Number(card.dataset.index)); } });
    card.addEventListener('mousemove', (event) => {
      if (reducedMotion || window.matchMedia('(pointer: coarse)').matches) return;
      const rect = card.getBoundingClientRect();
      const x = (event.clientX - rect.left) / rect.width - .5;
      const y = (event.clientY - rect.top) / rect.height - .5;
      card.style.transform = `perspective(900px) rotateX(${y * -2.5}deg) rotateY(${x * 2.5}deg)`;
    });
    card.addEventListener('mouseleave', () => { card.style.transform = ''; });
  });
}

