function initPreloader() {
  const preloader = qs('#preloader');
  if (reducedMotion) { preloader.remove(); return; }
  const letters = qsa('#preloader-name span');
  if (window.gsap) {
    gsap.to(letters, { y: 0, duration: .75, stagger: .06, ease: 'power3.out' });
    gsap.to('#preloader-line span', { width: '100%', duration: 1.35, ease: 'power2.inOut' });
  } else { letters.forEach(letter => letter.style.transform = 'translateY(0)'); qs('#preloader-line span').style.width = '100%'; }
  let value = 0;
  const timer = setInterval(() => {
    value = Math.min(100, value + Math.ceil(Math.random() * 8));
    qs('#counter').textContent = value;
    if (value >= 100) {
      clearInterval(timer); qs('#preloader-status').textContent = 'READY';
      setTimeout(() => { preloader.style.transform = 'translateY(-100%)'; preloader.style.transition = 'transform .85s cubic-bezier(.76,0,.24,1)'; setTimeout(() => preloader.remove(), 900); revealHero(); }, 250);
    }
  }, 38);
}
function revealHero() {
  if (!window.gsap || reducedMotion) { qsa('.mask > span, .reveal-up, .hero .text-reveal').forEach(el => el.classList.add('is-revealed')); return; }
  gsap.to('.hero .mask > span', { y: 0, duration: 1, stagger: .11, delay: .15, ease: 'power4.out' });
  gsap.to('.hero .reveal-up', { opacity: 1, y: 0, duration: .7, delay: .35, ease: 'power3.out' });
  gsap.to('.hero .text-reveal', { opacity: 1, y: 0, duration: .7, delay: .65, ease: 'power3.out' });
}

function setupScroll() {
  const progress = qs('.scroll-progress span');
  const header = qs('#site-header');
  window.addEventListener('scroll', () => {
    const max = document.documentElement.scrollHeight - window.innerHeight;
    progress.style.width = `${max > 0 ? (window.scrollY / max) * 100 : 0}%`;
    header.classList.toggle('is-scrolled', window.scrollY > 24);
    if (window.scrollY > lastScrollY && window.scrollY > 100) header.classList.add('is-hidden'); else header.classList.remove('is-hidden');
    lastScrollY = window.scrollY;
  }, { passive: true });
  if (window.gsap && window.ScrollTrigger && !reducedMotion) {
    gsap.registerPlugin(ScrollTrigger);
    gsap.utils.toArray('.reveal-lines, .text-reveal').forEach(el => gsap.to(el, { opacity: 1, y: 0, duration: .85, ease: 'power3.out', scrollTrigger: { trigger: el, start: 'top 88%', once: true } }));
    gsap.utils.toArray('.case-study__hero img').forEach(img => gsap.to(img, { yPercent: 10, ease: 'none', scrollTrigger: { trigger: img, scroller: '#case-scroll', start: 'top top', end: 'bottom top', scrub: true } }));
  } else {
    const observer = new IntersectionObserver(entries => entries.forEach(entry => { if (entry.isIntersecting) entry.target.classList.add('is-revealed'); }), { threshold: .12 });
    qsa('.reveal-lines, .text-reveal').forEach(el => observer.observe(el));
  }
  setupProcess();
}
function setupProcess() {
  const steps = qsa('.process-step'); const line = qs('.process-line span');
  const observer = new IntersectionObserver(entries => entries.forEach(entry => { if (entry.isIntersecting) { const index = steps.indexOf(entry.target); steps.forEach((step, i) => step.classList.toggle('is-active', i <= index)); if (window.innerWidth < 901) line.style.height = `${Math.min(100, (index / (steps.length - 1)) * 100)}%`; else line.style.width = `${Math.min(100, (index / (steps.length - 1)) * 100)}%`; } }), { threshold: .65 });
  steps.forEach(step => observer.observe(step));
}

function setupNavigation() {
  const menu = qs('#mobile-menu'); const toggle = qs('.menu-toggle');
  const closeMenu = () => { menu.classList.remove('is-open'); menu.setAttribute('aria-hidden','true'); toggle.setAttribute('aria-expanded','false'); document.body.classList.remove('is-locked'); };
  toggle.addEventListener('click', () => { const isOpen = menu.classList.toggle('is-open'); menu.setAttribute('aria-hidden', String(!isOpen)); toggle.setAttribute('aria-expanded', String(isOpen)); document.body.classList.toggle('is-locked', isOpen); });
  qsa('.mobile-menu a').forEach(link => link.addEventListener('click', closeMenu));
  qs('#close-case').addEventListener('click', closeCase); qs('#next-project').addEventListener('click', () => openCase((currentProject + 1) % projects.length));
  qs('#close-lightbox').addEventListener('click', closeLightbox); qs('#lightbox-prev').addEventListener('click', () => stepLightbox(-1)); qs('#lightbox-next').addEventListener('click', () => stepLightbox(1));
  document.addEventListener('keydown', event => { if (event.key === 'Escape') { if (qs('#lightbox').classList.contains('is-open')) closeLightbox(); else if (qs('#case-study').classList.contains('is-open')) closeCase(); } if (qs('#lightbox').classList.contains('is-open') && event.key === 'ArrowRight') stepLightbox(1); if (qs('#lightbox').classList.contains('is-open') && event.key === 'ArrowLeft') stepLightbox(-1); });
  qsa('.filter-chip').forEach(chip => chip.addEventListener('click', () => {
    qsa('.filter-chip').forEach(item => { item.classList.remove('is-active'); item.setAttribute('aria-selected','false'); }); chip.classList.add('is-active'); chip.setAttribute('aria-selected','true');
    const next = chip.dataset.filter; const cards = qsa('.project-card');
    if (window.gsap && cards.length && !reducedMotion) gsap.to(cards, { opacity: 0, scale: .96, duration: .25, stagger: .02, onComplete: () => { currentFilter = next; renderProjects(next); } }); else { currentFilter = next; renderProjects(next); }
  }));
  qs('#copy-email').addEventListener('click', async () => { const email = qs('#copy-email').dataset.email; try { await navigator.clipboard.writeText(email); } catch (_) {} const toast = qs('#toast'); toast.classList.add('is-visible'); setTimeout(() => toast.classList.remove('is-visible'), 1800); });
  qsa('[data-placeholder]').forEach(link => link.addEventListener('click', event => { event.preventDefault(); const toast = qs('#toast'); toast.textContent = `${link.dataset.placeholder} — Add detail here`; toast.classList.add('is-visible'); setTimeout(() => { toast.classList.remove('is-visible'); toast.textContent = 'Copied ✓'; }, 1900); }));
}

function setupCursor() {
  if (!window.matchMedia('(pointer: fine)').matches || reducedMotion) return;
  document.body.classList.add('has-cursor'); const dot = qs('.cursor-dot'); const ring = qs('.cursor-ring');
  let x = window.innerWidth / 2, y = window.innerHeight / 2, ringX = x, ringY = y;
  window.addEventListener('mousemove', event => { x = event.clientX; y = event.clientY; dot.style.left = `${x}px`; dot.style.top = `${y}px`; });
  const tick = () => { ringX += (x - ringX) * .17; ringY += (y - ringY) * .17; ring.style.left = `${ringX}px`; ring.style.top = `${ringY}px`; requestAnimationFrame(tick); }; tick();
  document.addEventListener('mouseover', event => { const card = event.target.closest('.project-card'); const link = event.target.closest('a,button'); ring.classList.toggle('is-view', !!card); ring.classList.toggle('is-link', !!link && !card); dot.classList.toggle('is-link', !!link && !card); });
  qsa('.magnetic').forEach(item => item.addEventListener('mousemove', event => { const rect = item.getBoundingClientRect(); const dx = (event.clientX - (rect.left + rect.width / 2)) * .18; const dy = (event.clientY - (rect.top + rect.height / 2)) * .18; item.style.transform = `translate(${dx}px,${dy}px)`; }));
  qsa('.magnetic').forEach(item => item.addEventListener('mouseleave', () => { item.style.transform = ''; }));
}

function setupTouchLightbox() {
  let startX = 0; const lightbox = qs('#lightbox');
  lightbox.addEventListener('touchstart', event => { startX = event.changedTouches[0].clientX; }, { passive: true });
  lightbox.addEventListener('touchend', event => { const delta = event.changedTouches[0].clientX - startX; if (Math.abs(delta) > 45) stepLightbox(delta < 0 ? 1 : -1); }, { passive: true });
}

function init() {
  renderProjects(); initPreloader(); revealHero(); setupScroll(); setupNavigation(); setupCursor(); setupTouchLightbox();
}
window.addEventListener('load', init);
